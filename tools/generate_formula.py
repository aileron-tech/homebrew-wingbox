"""Print Formula/wingbox.rb for a Wingbox release, from the PyPI metadata.

usage: python3 tools/generate_formula.py [VERSION] > Formula/wingbox.rb

Without VERSION the newest final release in the PyPI index is used (read from
the index of files, not from the "latest" metadata page, which a cache can
serve stale for a while after an upload). The formula installs the
Wingbox wheel and the wheels of its pinned dependencies; every file is pinned
by the sha256 that PyPI publishes, so pip refuses anything else.
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from dataclasses import dataclass
from typing import Any, Callable

PACKAGE = "wingbox"
PYTHON = "3.13"
INDEX = "https://pypi.org/pypi"
SIMPLE = "https://pypi.org/simple"
SIMPLE_JSON = "application/vnd.pypi.simple.v1+json"
_FINAL = re.compile(r"^\d+(\.\d+)*$")
# Wheels a Homebrew Python can load: this interpreter or the stable ABI, on macOS or glibc Linux.
_INTERPRETER = re.compile(rf"-(cp{PYTHON.replace('.', '')}-cp{PYTHON.replace('.', '')}|cp3\d+-abi3|py3-none)-")
_PLATFORM = re.compile(r"(macosx_\d+_\d+_(x86_64|arm64|universal2)|manylinux\S*_(x86_64|aarch64)|-any)\.whl$")
_PIN = re.compile(r"^([A-Za-z0-9._-]+)==([A-Za-z0-9._+!-]+)$")

Fetch = Callable[[str], dict[str, Any]]


@dataclass(frozen=True)
class Wheel:
    filename: str
    url: str
    sha256: str


@dataclass(frozen=True)
class Pinned:
    name: str
    version: str
    wheels: tuple[Wheel, ...]


@dataclass(frozen=True)
class Release:
    version: str
    wheel: Wheel
    dependencies: tuple[Pinned, ...]


class MetadataError(Exception):
    pass


def usable(filename: str) -> bool:
    return bool(_INTERPRETER.search(filename) and _PLATFORM.search(filename))


def wheels_of(metadata: dict[str, Any]) -> tuple[Wheel, ...]:
    files = [f for f in metadata["urls"] if f["packagetype"] == "bdist_wheel" and not f.get("yanked") and usable(f["filename"])]
    return tuple(Wheel(f["filename"], f["url"], f["digests"]["sha256"]) for f in sorted(files, key=lambda f: f["filename"]))


def pins_of(requires_dist: list[str] | None) -> tuple[tuple[str, str], ...]:
    """The required dependencies; each must be pinned to one version. Extras are left out."""
    pins: list[tuple[str, str]] = []
    for line in requires_dist or []:
        requirement, _, marker = line.partition(";")
        if "extra ==" in marker:
            continue
        found = _PIN.match(requirement.strip().replace(" ", ""))
        if not found or marker.strip():
            raise MetadataError(f"dependency is not pinned to one version: {line}")
        pins.append((found.group(1).lower(), found.group(2)))
    return tuple(sorted(pins))


def newest_final(versions: list[str]) -> str:
    """The highest version made of numbers only (no pre-release, dev or post marker)."""
    final = [version for version in versions if _FINAL.match(version)]
    if not final:
        raise MetadataError("the index lists no final release")
    return max(final, key=lambda version: tuple(int(part) for part in version.split(".")))


def read_release(fetch: Fetch, version: str) -> Release:
    metadata = fetch(f"{INDEX}/{PACKAGE}/{version}/json")
    if metadata["info"]["version"] != version:
        raise MetadataError(f"asked for {version}, the index answered {metadata['info']['version']}")
    own = wheels_of(metadata)
    if len(own) != 1:
        raise MetadataError(f"expected one {PACKAGE} wheel, found {len(own)}")
    dependencies: list[Pinned] = []
    for name, pinned_version in pins_of(metadata["info"]["requires_dist"]):
        dependency = fetch(f"{INDEX}/{name}/{pinned_version}/json")
        if pins_of(dependency["info"]["requires_dist"]):
            raise MetadataError(f"{name} has required dependencies of its own; pin them in {PACKAGE}")
        wheels = wheels_of(dependency)
        for platform in ("macosx", "manylinux"):
            if not any(platform in wheel.filename or wheel.filename.endswith("-any.whl") for wheel in wheels):
                raise MetadataError(f"{name} {pinned_version} has no {platform} wheel for Python {PYTHON}")
        dependencies.append(Pinned(name, pinned_version, wheels))
    return Release(metadata["info"]["version"], own[0], tuple(dependencies))


def requirements(release: Release) -> str:
    lines: list[str] = []
    for dependency in release.dependencies:
        hashes = " \\\n".join(f"    --hash=sha256:{wheel.sha256}" for wheel in dependency.wheels)
        lines.append(f"{dependency.name}=={dependency.version} \\\n{hashes}")
    return "\n".join(lines)


def formula(release: Release) -> str:
    pinned = "\n".join(("      " + line) if line else "" for line in requirements(release).split("\n"))
    return f'''# Generated by tools/generate_formula.py from the PyPI metadata of Wingbox {release.version}. Do not edit by hand.
class Wingbox < Formula
  include Language::Python::Virtualenv

  desc "Map of your codebase for AI coding agents"
  homepage "https://wingbox.dev"
  url "{release.wheel.url}", using: :nounzip
  version "{release.version}"
  sha256 "{release.wheel.sha256}"
  license "MIT"

  depends_on "python@{PYTHON}"

  def install
    python = formula_opt_bin("python@{PYTHON}")/"python{PYTHON}"
    virtualenv_create(libexec, "python{PYTHON}", system_site_packages: false)
    # The wheels of the pinned dependencies, by the sha256 PyPI publishes for each.
    (buildpath/"requirements.txt").write <<~EOS
{pinned}
    EOS
    pip = [python, "-m", "pip", "--python=#{{libexec}}/bin/python", "install",
           "--no-deps", "--only-binary=:all:", "--disable-pip-version-check", "--no-input"]
    system(*pip, "--require-hashes", "-r", buildpath/"requirements.txt")
    system(*pip, buildpath/"{release.wheel.filename}")
    bin.install_symlink libexec/"bin/wingbox"
  end

  def caveats
    <<~EOS
      Set up your coding assistants (Claude Code, Codex, Cursor, Copilot):
        wingbox install
      Upgrade with:
        brew upgrade wingbox
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/wingbox --version")
    (testpath/"app").mkpath
    (testpath/"app/__init__.py").write ""
    (testpath/"app/price.py").write "def total(items):\\n    return sum(items)\\n"
    (testpath/"app/cart.py").write "from app.price import total\\n\\n\\ndef checkout(items):\\n    return total(items)\\n"
    system bin/"wingbox", "build", testpath
    assert_path_exists testpath/".wingbox/index.sexp"
    assert_match "app/cart.py", shell_output("#{{bin}}/wingbox impact app/price.py")
  end
end
'''


def fetch_json(url: str) -> dict[str, Any]:
    request = urllib.request.Request(url, headers={"Accept": SIMPLE_JSON if url.startswith(SIMPLE) else "application/json"})
    with urllib.request.urlopen(request, timeout=30) as response:  # noqa: S310 - fixed https index URL
        return json.load(response)


def main(arguments: list[str]) -> int:
    try:
        version = arguments[0] if arguments else newest_final(fetch_json(f"{SIMPLE}/{PACKAGE}/")["versions"])
        release = read_release(fetch_json, version)
    except (MetadataError, OSError, KeyError) as error:
        print(f"generate_formula: {error}", file=sys.stderr)
        return 1
    sys.stdout.write(formula(release))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
